def next_sigma(sigma: torch.Tensor, schedule: torch.Tensor) -> float | None:
    """The next smaller native 50-step sigma, excluding unstable near-zero loss."""
    smaller = schedule[schedule < float(sigma) - 1e-7]
    if not len(smaller):
        return None
    value = float(smaller.max())
    return value if value >= 0.1 else None


def reconstruction_terms(runtime, noisy, timestep, target, clean, hr, camera,
                         prepared, sigma, *, mode: str, rgb_view: int,
                         schedule: torch.Tensor):
    shape = tuple(clean.shape[2:])
    prediction = runtime.module.predict(
        runtime.dit, noisy, timestep, None, prepared, camera, shape
    )
    flow = flow_matching_loss(prediction, target)
    recover = flow.new_zeros(())
    rgb = flow.new_zeros(())
    if mode in {"recover", "both"}:
        lower = next_sigma(sigma, schedule)
        if lower is not None:
            # The next input is generated by the model. The exact HR target at
            # that state is (z_next - z_HR) / lower, not epsilon - z_HR.
            z_next = (noisy + (lower - sigma) * prediction).detach()
            v_next = runtime.module.predict(
                runtime.dit, z_next, torch.full_like(timestep, lower * 1000),
                None, prepared, camera, shape,
            )
            recover = flow_matching_loss(v_next, (z_next - clean) / lower)
    if mode in {"rgb", "both"}:
        estimated_clean = noisy - sigma * prediction
        decoded = runtime.vae.decode_multiview(
            estimated_clean[:, :, rgb_view:rgb_view + 1]
        )
        rgb = F.mse_loss(decoded.float(), hr[:, :, rgb_view:rgb_view + 1].float())
    return flow, recover, rgb


def gradient_norm(loss, parameters) -> float:
    grads = torch.autograd.grad(loss, parameters, retain_graph=True, allow_unused=True)
    value = math.sqrt(sum(float(g.detach().float().square().sum()) for g in grads if g is not None))
    if not math.isfinite(value) or value <= 0:
        raise RuntimeError("auxiliary gradient is non-finite or zero")
    return value


def indexed_generator(seed: int, index: int, offset: int, *, device: str = "cpu"):
    return torch.Generator(device=device).manual_seed(seed * 1_000_003 + index * 101 + offset)


def ordinary_batch(config, seed: int, index: int, device: torch.device,
                   sigma: torch.Tensor, noise_seed: int):
    group_gen = indexed_generator(seed, index, 11)
    scene = config.train_scenes[index % len(config.train_scenes)]
    indices, hr, lr, camera = st._load_group(
        RUNTIME_ROOT / "datasets/nerf_synthetic", scene, "train", config,
        group_gen, device,
    )
    dropped = bool(torch.rand((), generator=indexed_generator(seed, index, 23)) < config.target_lr_dropout)
    if dropped:
        lr = lr.clone()
        lr[:, :, 0] = 0
    noise_gen = indexed_generator(seed, noise_seed, 37, device="cuda")
    return scene, indices, hr, lr, camera, dropped, noise_gen, sigma


def second_target(first: int, auxiliaries: list[int], centers: torch.Tensor) -> int:
    directions = F.normalize(centers.float(), dim=-1)
    cosine = (directions @ directions[first]).clamp(-1, 1)
    angles = torch.rad2deg(torch.acos(cosine))
    choices = [
        index for index, angle in enumerate(angles.tolist())
        if index not in {first, *auxiliaries} and 15 <= angle <= 45
    ]
    if not choices:
        raise RuntimeError("no second target camera in the frozen 15–45 degree window")
    return min(choices, key=lambda index: (abs(float(angles[index]) - 30), index))


def paired_group(config, seed: int, step: int, device: torch.device):
    scene = config.train_scenes[(step - 1) % len(config.train_scenes)]
    indices, hr_a, lr_a, camera_a = st._load_group(
        RUNTIME_ROOT / "datasets/nerf_synthetic", scene, "train", config,
        indexed_generator(seed, step, 71), device,
    )
    _, sequence = st._scene_data(
        RUNTIME_ROOT / "datasets/nerf_synthetic" / scene,
        config, st.Split.TRAIN,
    )
    all_camera = st._camera(sequence.observations, config.image_size, torch.device("cpu"))
    centers = all_camera.T_world_from_camera[0, :, :3, 3]
    target_b = second_target(indices[0], indices[1:], centers)
    other = [target_b, *indices[1:]]
    _, hr_b, lr_b, camera_b = st._load_indices(
        RUNTIME_ROOT / "datasets/nerf_synthetic", scene, "train",
        other, config, device,
    )
    if not torch.equal(lr_a[:, :, 1:], lr_b[:, :, 1:]):
        raise RuntimeError("paired groups do not share identical auxiliary LR")
    if not torch.equal(camera_a.K[:, 1:], camera_b.K[:, 1:]) or not torch.equal(
        camera_a.T_world_from_camera[:, 1:], camera_b.T_world_from_camera[:, 1:]
    ):
        raise RuntimeError("paired groups do not share identical auxiliary poses")
    return scene, indices, other, (hr_a, lr_a, camera_a), (hr_b, lr_b, camera_b)


def pair_loss(runtime, config, seed: int, step: int, mode: str):
    scene, indices_a, indices_b, group_a, group_b = paired_group(
        config, seed, step, runtime.device
    )
    with torch.no_grad():
        clean_a = runtime.vae.encode_multiview(group_a[0])
        clean_b = runtime.vae.encode_multiview(group_b[0])
    noise = torch.randn(
        clean_a.shape,
        generator=indexed_generator(seed, step, 83, device="cuda"),
        device=runtime.device, dtype=clean_a.dtype,
    )
    if clean_a.shape != clean_b.shape or not torch.equal(clean_a[:, :, 1:], clean_b[:, :, 1:]):
        raise RuntimeError("paired HR latents have different auxiliaries")
    losses = []
    for clean, (_, lr, camera) in ((clean_a, group_a), (clean_b, group_b)):
        if mode == "challenge":
            lr = lr.clone()
            lr[:, :, 0] = 0
            if torch.count_nonzero(lr[:, :, 0]):
                raise RuntimeError("paired target LR was not hidden")
        prepared = runtime.module.prepare_multiview(
            lr, camera, tuple(clean.shape[2:]),
            (config.image_size, config.image_size),
        )
        prediction = runtime.module.predict(
            runtime.dit, noise, torch.full((1,), 1000., device=runtime.device),
            None, prepared, camera, tuple(clean.shape[2:]),
        )
        losses.append(flow_matching_loss(prediction[:, :, :1], (noise - clean)[:, :, :1]))
    return torch.stack(losses).mean(), {"scene": scene, "a": indices_a, "b": indices_b}


def sample_terms(runtime, config, seed, step, micro, sigma, schedule, mode):
    index = (step - 1) * config.gradient_accumulation + micro
    scene, indices, hr, lr, camera, dropped, generator, sigma = ordinary_batch(
        config, seed, index, runtime.device, sigma, index,
    )
    with torch.no_grad():
        clean = runtime.vae.encode_multiview(hr)
    noise = torch.randn(clean.shape, generator=generator, device=runtime.device, dtype=clean.dtype)
    noisy, timestep, target = flow_matching_pair(clean, noise, sigma.reshape(1).to(runtime.device))
    prepared = runtime.module.prepare_multiview(
        lr, camera, tuple(clean.shape[2:]), (config.image_size, config.image_size)
    )
    terms = reconstruction_terms(
        runtime, noisy, timestep, target, clean, hr, camera, prepared,
        sigma.to(runtime.device), mode=mode,
        rgb_view=index % config.views, schedule=schedule,
    )
    return terms, {"scene": scene, "views": indices, "sigma": float(sigma), "target_lr_dropped": dropped}


def calibrate(runtime, config, seed: int, output: Path):
    schedule = unipc_schedule(
        FlowSamplingConfig(config.sampling_steps, config.sampling_shift), device="cpu"
    )[1][:-1]
    cycle = SigmaCycle(FlowSamplingConfig(config.sampling_steps, config.sampling_shift),
                       seed=seed + 1000, strategy="balanced")
    parameters = [p for p in runtime.module.parameters() if p.requires_grad]
    ratios_recover, ratios_rgb = [], []
    for index in range(8):
        sigma = cycle.next()
        (flow, recover, rgb), _ = sample_terms(
            runtime, config, seed, 1, index, sigma, schedule, "both"
        )
        base = gradient_norm(flow, parameters)
        if base <= 0 or not math.isfinite(base):
            raise RuntimeError("non-finite or zero flow gradient during calibration")
        if recover.requires_grad and float(recover) > 0:
            ratios_recover.append(base / gradient_norm(recover, parameters))
        ratios_rgb.append(base / gradient_norm(rgb, parameters))
        del flow, recover, rgb
        torch.cuda.empty_cache()
    if not ratios_recover or not ratios_rgb:
        raise RuntimeError("loss calibration has no valid auxiliary gradients")
    weight_recover = 0.2 * float(torch.tensor(ratios_recover).median())
    weight_rgb = 0.1 * float(torch.tensor(ratios_rgb).median())
    if not all(math.isfinite(x) and 0.0001 <= x <= 100 for x in (weight_recover, weight_rgb)):
        raise RuntimeError("calibrated loss weight outside safe range")
    payload = {
        "recover": weight_recover, "rgb": weight_rgb,
        "gradient_ratio_targets": {"recover": 0.2, "rgb": 0.1},
        "batches": 8, "seed": seed, "parent_sha256": sha256(PARENT),
    }
    frozen_json(output, payload)
    return payload


def train(args):
    config = load_stage3_config(args.config)
    if config.camera_rank_weight or config.pairing_supervision or config.correct_image_ssim_weight is not None:
        raise ValueError("loss experiment requires rank and old image terms disabled")
    if config.views != 4 or config.train_scenes != ("lego",):
        raise ValueError("screening protocol requires Lego and four views")
    if args.pair_mode != "none" and args.loss_mode not in LOSS_MODES:
        raise ValueError("invalid paired loss configuration")
    st._seed_all(args.seed)
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    calibration = json.loads(args.calibration.read_text())
    if calibration["parent_sha256"] != sha256(PARENT):
        raise RuntimeError("parent checkpoint hash changed")
    prior = sorted(output.glob("stage3_step_*.pt"))
    if prior:
        checkpoint = prior[-1]
        payload = torch.load(checkpoint, map_location="cpu", weights_only=True)
        if payload["provenance"]["experiment"] != args.experiment:
            raise RuntimeError("resume experiment identity mismatch")
        if (payload["provenance"]["loss_mode"] != args.loss_mode
                or payload["provenance"]["pair_mode"] != args.pair_mode
                or payload["provenance"]["source_sha256"] != sha256(Path(__file__))
                or payload["provenance"]["calibration_sha256"] != sha256(args.calibration)):
            raise RuntimeError("resume protocol or source changed")
        start_step = int(payload["step"]) + 1
        runtime_model = runtime(config, checkpoint)
    else:
        if any(output.iterdir()):
            raise RuntimeError("nonempty training directory without checkpoint")
        checkpoint = None
        start_step = 1
        runtime_model = runtime(config, PARENT, initialization=True)
    runtime_model.module.train()
    runtime_model.dit.model.eval().requires_grad_(False)
    runtime_model.vae.model.model.eval().requires_grad_(False)
    parameters = [p for p in runtime_model.module.parameters() if p.requires_grad]
    manifest_path = output / "run_manifest.json"
    if checkpoint is None:
        initial_digest = trainable_digest(runtime_model.module)
        frozen_json(manifest_path, {
            "experiment": args.experiment, "loss_mode": args.loss_mode,
            "pair_mode": args.pair_mode, "seed": args.seed,
            "config_sha256": sha256(args.config),
            "calibration_sha256": sha256(args.calibration),
            "source_sha256": sha256(Path(__file__)),
            "parent_sha256": sha256(PARENT),
            "initial_trainable_sha256": initial_digest,
            "trainable_parameters": sum(p.numel() for p in parameters),
        })
    else:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if (manifest["config_sha256"] != sha256(args.config)
                or manifest["source_sha256"] != sha256(Path(__file__))
                or manifest["calibration_sha256"] != sha256(args.calibration)):
            raise RuntimeError("resume run manifest drift")
        initial_digest = manifest["initial_trainable_sha256"]
    optimizer = torch.optim.AdamW(parameters, lr=config.learning_rate,
                                   weight_decay=config.weight_decay)
    if checkpoint is not None:
        optimizer.load_state_dict(payload["training_state"]["optimizer"])
    schedule = unipc_schedule(
        FlowSamplingConfig(config.sampling_steps, config.sampling_shift), device="cpu"
    )[1][:-1]
    cycle = SigmaCycle(FlowSamplingConfig(config.sampling_steps, config.sampling_shift),
                       seed=args.seed + 1000, strategy="balanced")
    for _ in range((start_step - 1) * config.gradient_accumulation):
        cycle.next()
    provenance = {
        "experiment": args.experiment, "loss_mode": args.loss_mode,
        "pair_mode": args.pair_mode, "calibration_sha256": sha256(args.calibration),
        "parent_checkpoint": str(PARENT), "parent_sha256": sha256(PARENT),
        "source_sha256": sha256(Path(__file__)), "training_seed": args.seed,
        "initial_trainable_sha256": initial_digest,
    }
    log = output / "train_steps.jsonl"
    if checkpoint is not None and sum(1 for _ in log.open()) != start_step - 1:
        raise RuntimeError("JSONL/checkpoint step mismatch")
    elapsed_prior = 0.0
    if checkpoint is not None:
        with log.open(encoding="utf-8") as stream:
            for line in stream:
                elapsed_prior = json.loads(line)["elapsed_seconds"]
    started = time.perf_counter()
    for step in range(start_step, config.steps + 1):
        optimizer.zero_grad(set_to_none=True)
        rows = []
        for micro in range(config.gradient_accumulation):
            sigma = cycle.next()
            terms, metadata = sample_terms(
                runtime_model, config, args.seed, step, micro, sigma,
                schedule, args.loss_mode,
            )
            flow, recover, rgb = terms
            loss = flow
            if args.loss_mode in ("recover", "both"):
                loss = loss + calibration["recover"] * recover
            if args.loss_mode in ("rgb", "both"):
                loss = loss + calibration["rgb"] * rgb
            (loss / config.gradient_accumulation).backward()
            rows.append({**metadata, "flow": float(flow.detach()),
                         "recover": float(recover.detach()), "rgb": float(rgb.detach()),
                         "loss": float(loss.detach())})
        pair_info = None
        if args.pair_mode != "none" and step % 4 == 0:
            pair, pair_info = pair_loss(runtime_model, config, args.seed, step, args.pair_mode)
            (0.25 * pair).backward()
            pair_info["loss"] = float(pair.detach())
        if any(p.grad is None or not torch.isfinite(p.grad).all() for p in parameters):
            raise RuntimeError("missing or non-finite trainable gradient")
        if any(p.grad is not None for p in runtime_model.dit.model.parameters()):
            raise RuntimeError("frozen Wan received a gradient")
        grad_norm = float(torch.nn.utils.clip_grad_norm_(parameters, config.gradient_clip))
        optimizer.step()
        row = {
            "step": step, "micro": rows, "pair": pair_info,
            "loss": sum(item["loss"] for item in rows) / len(rows)
                    + (0.25 * pair_info["loss"] if pair_info else 0),
            "gradient_norm": grad_norm,
            "elapsed_seconds": elapsed_prior + time.perf_counter() - started,
            "peak_gpu_memory_mib": torch.cuda.max_memory_allocated() / 2**20,
        }
        with log.open("a", encoding="utf-8") as stream:
            stream.write(json.dumps(row, sort_keys=True, allow_nan=False) + "\n")
        csv_path = output / "train_steps.csv"
        with csv_path.open("a", newline="", encoding="utf-8") as stream:
            writer = csv.DictWriter(stream, fieldnames=(
                "step", "loss", "gradient_norm", "elapsed_seconds", "peak_gpu_memory_mib",
                "mean_flow", "mean_recover", "mean_rgb", "pair_loss",
            ))
            if step == 1:
                writer.writeheader()
            writer.writerow({
                "step": step, "loss": row["loss"],
                "gradient_norm": grad_norm, "elapsed_seconds": row["elapsed_seconds"],
                "peak_gpu_memory_mib": row["peak_gpu_memory_mib"],
                "mean_flow": sum(item["flow"] for item in rows) / len(rows),
                "mean_recover": sum(item["recover"] for item in rows) / len(rows),
                "mean_rgb": sum(item["rgb"] for item in rows) / len(rows),
                "pair_loss": "" if pair_info is None else pair_info["loss"],
            })
        if step % config.checkpoint_every == 0 or step == config.steps:
            save_stage3_checkpoint(
                output / f"stage3_step_{step:04d}.pt", runtime_model.module,
                config=config.to_dict(), step=step, provenance=provenance,
                training_state={"optimizer": optimizer.state_dict(), "step": step},
            )
        if step == 1 or step % 25 == 0:
            print(json.dumps({"step": step, "loss": row["loss"],
                              "elapsed_seconds": row["elapsed_seconds"]}), flush=True)


def preflight(args):
    config = load_stage3_config(args.config)
    if args.output is None:
        raise ValueError("preflight requires --output")
    output = args.output.resolve()
    if output.exists():
        raise RuntimeError("preflight output already exists")
    output.mkdir(parents=True)
    st._seed_all(args.seed)
    model = runtime(config, PARENT, initialization=True)
    model.module.train()
    model.dit.model.eval().requires_grad_(False)
    model.vae.model.model.eval().requires_grad_(False)
    frozen = {
        "wan": next(model.dit.model.parameters()).detach().clone(),
        "vae": next(model.vae.model.model.parameters()).detach().clone(),
        "lr": next(model.module.conditioner.projector.parameters()).detach().clone(),
    }
    sigma = torch.tensor(0.5)
    schedule = unipc_schedule(
        FlowSamplingConfig(config.sampling_steps, config.sampling_shift), device="cpu"
    )[1][:-1]
    (flow, recover, rgb), metadata = sample_terms(
        model, config, args.seed, 1, 0, sigma, schedule, "both"
    )
    loss = flow + 0.2 * recover + 0.1 * rgb
    loss.backward()
    parameters = [p for p in model.module.parameters() if p.requires_grad]
    if any(p.grad is None or not torch.isfinite(p.grad).all() for p in parameters):
        raise RuntimeError("preflight found missing or non-finite trainable gradients")
    groups = {
        "bridge": st._module_grad_norm(model.module.conditioner.bridge),
        "rre": st._module_grad_norm(model.module.geometry),
        "fusion": st._module_grad_norm(model.module.fusion),
    }
    if any(not math.isfinite(value) or value <= 0 for value in groups.values()):
        raise RuntimeError(f"preflight gradient group failure: {groups}")
    if (not torch.equal(frozen["wan"], next(model.dit.model.parameters()))
            or not torch.equal(frozen["vae"], next(model.vae.model.model.parameters()))
            or not torch.equal(frozen["lr"], next(model.module.conditioner.projector.parameters()))):
        raise RuntimeError("frozen parameter changed")
    if any(p.grad is not None for p in model.dit.model.parameters()):
        raise RuntimeError("Wan received a gradient")
    paired, pair_metadata = pair_loss(model, config, args.seed, 4, "challenge")
    if not torch.isfinite(paired):
        raise RuntimeError("paired positive loss is non-finite")
    loss_values = {"flow": float(flow.detach()), "recover": float(recover.detach()),
                   "rgb": float(rgb.detach()), "pair": float(paired.detach())}
    model.module.eval()
    with torch.no_grad():
        _, _, hr, lr, camera, _, generator, _ = ordinary_batch(
            config, args.seed, 0, model.device, sigma, 0
        )
        clean = model.vae.encode_multiview(hr)
        noise = torch.randn(clean.shape, generator=generator, device=model.device, dtype=clean.dtype)
        noisy, timestep, _ = flow_matching_pair(clean, noise, sigma.reshape(1).to(model.device))
        prepared = model.module.prepare_multiview(lr, camera, tuple(clean.shape[2:]),
                                                  (config.image_size, config.image_size))
        before = model.module.predict(model.dit, noisy, timestep, None, prepared,
                                      camera, tuple(clean.shape[2:])).detach().cpu()
    checkpoint = output / "preflight_step_0000.pt"
    save_stage3_checkpoint(
        checkpoint, model.module, config=config.to_dict(), step=0,
        provenance={"experiment": args.experiment, "training_seed": args.seed},
    )
    del model, loss, flow, recover, rgb, paired, parameters, frozen
    del clean, noise, noisy, timestep, hr, lr, camera, prepared
    gc.collect()
    torch.cuda.empty_cache()
    reloaded = runtime(config, checkpoint)
    reloaded.module.eval()
    with torch.no_grad():
        _, _, hr, lr, camera, _, generator, _ = ordinary_batch(
            config, args.seed, 0, reloaded.device, sigma, 0
        )
        clean = reloaded.vae.encode_multiview(hr)
        noise = torch.randn(clean.shape, generator=generator, device=reloaded.device, dtype=clean.dtype)
        noisy, timestep, _ = flow_matching_pair(clean, noise, sigma.reshape(1).to(reloaded.device))
        prepared = reloaded.module.prepare_multiview(lr, camera, tuple(clean.shape[2:]),
                                                     (config.image_size, config.image_size))
        after = reloaded.module.predict(reloaded.dit, noisy, timestep, None, prepared,
                                        camera, tuple(clean.shape[2:])).detach().cpu()
    max_difference = float((before.float() - after.float()).abs().max())
    if max_difference > 1e-3:
        raise RuntimeError(f"preflight checkpoint reload differs: {max_difference}")
    frozen_json(output / "preflight.json", {
        "pass": True, "losses": loss_values,
        "gradient_norms": groups, "sample": metadata, "pair_sample": pair_metadata,
        "reload_max_difference": max_difference,
        "peak_gpu_memory_mib": torch.cuda.max_memory_allocated() / 2**20,
        "parent_sha256": sha256(PARENT), "checkpoint_sha256": sha256(checkpoint),
    })


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("preflight", "calibrate", "train"))
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--calibration", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--loss-mode", choices=LOSS_MODES, default="flow")
    parser.add_argument("--pair-mode", choices=PAIR_MODES, default="none")
    parser.add_argument("--experiment", default="stage3_loss_conditional_20260926")
    parser.add_argument("--seed", type=int, default=42)
    return parser.parse_args()


def main():
    args = parse_args()
    config = load_stage3_config(args.config)
    if args.command == "preflight":
        preflight(args)
    elif args.command == "calibrate":
        if args.calibration.exists():
            raise RuntimeError("calibration already exists")
        st._seed_all(args.seed)
        model = runtime(config, PARENT, initialization=True)
        model.module.train()
        calibrate(model, config, args.seed, args.calibration)
    else:
        if args.output is None:
            raise ValueError("train requires --output")
        train(args)


if __name__ == "__main__":
    main()
